// By Next.JS enforcement, need a "route.ts" file (this file) inside this directory "src\app\api\webhooks\stripe\route.ts" which can determines the logic when someone pays for a subscription. Using boilerplate provided below

// Webhook is a method of automating & integrating data or events btw different applications or systems over internet.  Application on one end can send real-time information to another application or service when event or trigger occurs (in this case, when user buys something).

// Webhook accepts raw body; it must be post-request; event you should handle

import { db } from "@/db";
import { stripe } from "@/lib/stripe";
import { headers } from "next/headers";
import type Stripe from "stripe";

export async function POST(request: Request) {
  const body = await request.text(); // contains the event data. Converts rawbody to a string 
  const signature = headers().get("Stripe-Signature") ?? ""; // used to verify that event is genuinely from Stripe

  // Limited inside block event that is type Stripe. Event which is provided by Stripe library and represent Stripe event object and this is type annotation for event.
  let event: Stripe.Event;

  // Validating this event comes from stripe because no user should be able to invoke this and give themselves the Pro Plan This API route is giving them the Pro Plan.
  // Uses the params to construct a "Stripe.Event" object and verify that event was sent by Stripe by generating its own signature from the "body" and "secret" params and compare it to "signature" params.
  try {
    // Constructs and verify event. If signature doesn't match, error is thrown
    event = stripe.webhooks.constructEvent(
      // Raw body of the incoming POST request from Stripe. It contains the event data sent by Stripe.
      body,
      // Signature generated by Stripe, included in the Stripe-Signature header of the request. Stripe generates this signature using a secret that only you and Stripe know (the webhook secret), and the body of the request.
      signature,
      // Stripe is sending this along with every request that we can check against if it's a request and see if the user pay for service
      process.env.STRIPE_WEBHOOK_SECRET || ""
    );
  } catch (err) {
    return new Response(
      `Webhook Error: ${err instanceof Error ? err.message : "Unknown Error"}`,
      { status: 400 }
    );
  }

  // Event data is expected to be an object containing info about checkout session, including metadata such as user ID.
  // The "as Stripe.Checkout.Session" part is a type cast in TypeScript. It’s telling TypeScript to treat "event.data.object" as a "Stripe.Checkout.Session" object. This allows you to access properties of "Stripe.Checkout.Session" on "event.data.object" without TypeScript throwing errors. "data" and "object" are both defined in Stripe APIs and "event.data.object" could be several different types of objects depending on the type of the event (it could be a Checkout.Session object, an Invoice object, a PaymentIntent object, etc.). But by casting it to "Stripe.Checkout.Session", you’re specifying that in this context, you expect it to be a "Checkout.Session object".
  const session = event.data.object as Stripe.Checkout.Session;

  // The metadata added from creating a stripeSession from tRPC API Endpoint in "src\trpc\index.ts" and can add user ID at the end since that is created inside and this to see if the session for this user exists, if user does not exists return 200 response
  if (!session?.metadata?.userId) {
    return new Response(null, {
      status: 200,
    });
  }

  // User buys for the first time, can add into database. This means user completed a checkout session (made the payment) and this code retrieves the subscription details from Stripe and then updates the user's record in the database with the subscription details.
  if (event.type === "checkout.session.completed") {
    const subscription = await stripe.subscriptions.retrieve(
      session.subscription as string
    );

    // Added in
    await db.user.update({
      where: {
        id: session.metadata.userId,
      },
      data: {
        stripeSubscriptionId: subscription.id,
        stripeCustomerId: subscription.customer as string,
        stripePriceId: subscription.items.data[0]?.price.id,
        stripeCurrentPeriodEnd: new Date(
          subscription.current_period_end * 1000
        ),
      },
    });
    // End of added code
  }

  // Monthly plan is renewed. Code retrieves the subscription details from Strip, then updates the user's record in the database with the new subscription end date and price ID
  if (event.type === "invoice.payment_succeeded") {
    // Retrieve the subscription details from Stripe.
    const subscription = await stripe.subscriptions.retrieve(
      session.subscription as string
    );
    // Added in
    await db.user.update({
      where: {
        stripeSubscriptionId: subscription.id, // Do this method since we already have the user
      },
      data: {
        stripePriceId: subscription.items.data[0]?.price.id,
        stripeCurrentPeriodEnd: new Date(
          subscription.current_period_end * 1000
        ),
      },
    });
    // End of the added code
  }

  // Lets Stripe know that the webhook event was received and processed successfully
  return new Response(null, { status: 200 });
}
