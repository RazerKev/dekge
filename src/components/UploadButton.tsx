"use client";

import { useState } from "react";
import { Dialog, DialogContent, DialogTrigger } from "./ui/dialog";
import { Button } from "./ui/button";

import Dropzone from "react-dropzone"; // Not destructure anyhything
import { Cloud, File, Loader2 } from "lucide-react";
import { Progress } from "./ui/progress";
import { useUploadThing } from "@/lib/uploadthing";
import { useToast } from "./ui/use-toast";
import { trpc } from "@/app/_trpc/client";
import { useRouter } from "next/navigation";

const UploadDropzone = () => {
  const router = useRouter(); // Needed for pushing and navigating the URL after getFile

  const [isUploading, setIsUploading] = useState<boolean>(false);
  const [uploadProgress, setUploadProgress] = useState<number>(0);

  const { toast } = useToast();

  // Returns a Promise of object or undefined so can await this action (further down in the code)
  const { startUpload } = useUploadThing("pdfUploader");

  // onSuccess callback to handle data sync with the Polling
  // Won't run with empty {}; Need to add '{mutate}' function to make this start polling. Named it 'startPolling' could be any name
  const { mutate: startPolling } = trpc.getFile.useMutation({
    onSuccess: (file) => {
      // onSuccess: There was a file & returned from 'src/trpc/index.ts'
      // To redirect the user to the file, need access to router.
      router.push(`/dashboard/${file.id}`);
    },
    // To do polling, add retry and it will continue indefinitently until it gets a successful response
    retry: true,
    retryDelay: 500, // half sec
  });

  //   Determinate Progress bar - Don't have access to an actual progress. Can define how it skips (in increments) and once done uploading, can skip to 100. Skip in increment since unsure in whatever percentage of choice but if stuck or not complement by the increment, progress bar will stay at 95% until fully complete.

  const startSimulatedProgress = () => {
    setUploadProgress(0); // Set to 0 for safety initalization

    const interval = setInterval(() => {
      // First arg have access to previous value when using state
      setUploadProgress((prevProgress) => {
        // Don't progress anymore / invalidating whole thing to prevet pass 95%
        if (prevProgress >= 95) {
          clearInterval(interval);
          return prevProgress; // Would be 95%
        }
        return prevProgress + 5; // '5' can be any value of increment
      });
    }, 500); // 500ms is set for interval
    return interval;
  };

  return (
    <Dropzone
      multiple={false}
      onDrop={async (acceptedFiles) => {
        setIsUploading(true);

        const progressInterval = startSimulatedProgress();

        // Handle File uploading from uploadThing. HOWEVER, does not mean file is in the database so have to do POLLING APPROACH (every couple of ms, the service/app (dekge) communicate and asks the api (created in index, 'getFile') if the file is there in DB, and API respond back with success response but IF NOT, then the service & api will keep 'polling' until it's there on success (all of this is asynchronous)) and check if exists in database using keys
        const res = await startUpload(acceptedFiles);

        // If no response, send a toast pop up error from ui.shadcn.com
        if (!res) {
          return toast({
            title: "Something went wrong",
            description: "Please try again later",
            variant: "destructive",
          });
        }

        // There is response, res, from Promise
        // 'fileResponse' can be named whatever
        // Taking first array element of the response since it's array
        const [fileResponse] = res;

        // 'key' is generated by uploadThing
        const key = fileResponse?.key;

        // Safety check if no key
        if (!key) {
          return toast({
            title: "Something went wrong",
            description: "Please try again later",
            variant: "destructive",
          });
        }

        //

        clearInterval(progressInterval); // Resetting after done, clear the interval
        setUploadProgress(100); // Done uploading

        // Add this last to start polling if there's a key
        startPolling({ key });

        // console.log(acceptedFiles);
      }}
    >
      {/* Followed based on Doc */}
      {/* 'getRootProps()' get props required for dran 'n' drop & use them on any element. 'getInputProps()' use the click and keydown behavior instead. 'acceptedFiles' is when user input the file  */}
      {({ getRootProps, getInputProps, acceptedFiles }) => (
        <div
          {...getRootProps()}
          className="border h-64 m-4 border-dashed border-gray-300 rounded-xl"
        >
          <div className="flex items-center justify-center h-full w-full">
            {/* Dropzone should be wrapped in a "div" instead of "label" to prevent react-dropzone opening file manager 2-3 times */}
            <div
              // htmlFor="dropzone-file" // This goes with the "label" tags above this comment that was removed in order to remove the file manager reopening 
              className="flex flex-col items-center justify-center w-full h-full rounded-lg cursor-pointer bg-gray-50 hover:bg-gray-100"
            >
              <div className="flex flex-col items-center justify-center pt-5 pb-6">
                <Cloud className="h-6 w-6 text-zinc-500 mb-2" />
                <p className="mb-2 text-sm text-zinc-700">
                  <span className="font-semibold">Click to upload</span> or drag
                  and drop.
                </p>
                <p className="text-xs text-zinc-500">PDF (up to 4MB)</p>
              </div>
              {/* If the file is upload (would be stored in 'acceptedFiles') and at the first index since only checking for one file */}
              {acceptedFiles && acceptedFiles[0] ? (
                <div className="max-w-xs bg-white flex items-center rounded-md overflow-hidden outline outline-[1px] outline-zinc-200 divide-x divide-zinc-200">
                  <div className="px-3 py-2 h-full grid place-content-center">
                    <File className="h-4 w-4 text-blue-500" />
                  </div>
                  <div className="px-3 py-2 h-full text-sm truncate">
                    {acceptedFiles[0].name}
                  </div>
                </div>
              ) : null}
              {isUploading ? (
                <div className="w-full mt-4 max-w-xs mx-auto">
                  <Progress
                    // Dynamic indicatorColor with '{}'
                    indicatorColor={
                      uploadProgress === 100 ? "bg-green-500" : "" // empty string to keep defaults remain for 'progress' component
                    }
                    value={uploadProgress}
                    className="h-1 w-full bg-zinc-200"
                  />
                  {/* If uploadProgress is done uploading, show redirect message */}
                  {uploadProgress === 100 ? (
                    <div className="flex gap-1 items-center justify-center text-sm text-zinc-700 text-center pt-2">
                      <Loader2 className="h-3 w-3 animate-spin" />
                      Redirecting...
                    </div>
                  ) : null}
                </div>
              ) : null}

              <input
                {...getInputProps} // Followed from Doc
                type="file"
                id="dropzone-file"
                className="hidden"
              />
            </div>
          </div>
        </div>
      )}
    </Dropzone>
  );
};

const UploadButton = () => {
  const [isOpen, setIsOpen] = useState(false);

  return (
    <Dialog
      open={isOpen}
      onOpenChange={(vissible) => {
        if (!vissible) {
          setIsOpen(vissible);
        }
      }}
    >
      <DialogTrigger onClick={() => setIsOpen(true)} asChild>
        {/* 'asChild' makes a custom button as not DialogTrigger inherited. The Button below is main/active */}
        <Button>Upload PDF</Button>
      </DialogTrigger>

      <DialogContent>
        <UploadDropzone />
      </DialogContent>
    </Dialog>
  );
};

export default UploadButton;
